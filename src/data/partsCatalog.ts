/**
 * Returns the exact right photo for an automotive spare part based on part name and characteristics.
 */
export function getPartPhoto(partName: string, fallback?: string): string {
  const name = (partName || '').toLowerCase();

  if (name.includes('alternator')) return alternatorImg;
  if (name.includes('starter')) return starterMotorImg;
  if (name.includes('rotor') || name.includes('disc') || name.includes('brake disc')) return brakeDiscRotorImg;
  if (name.includes('brake') || name.includes('pad') || name.includes('lining')) return brakePadsImg;
  if (name.includes('radiator') || name.includes('cooling core')) return radiatorImg;
  if (name.includes('shock') || name.includes('strut') || name.includes('absorber') || name.includes('damper')) return shockAbsorberImg;
  if (name.includes('stabilizer') || name.includes('sway bar') || name.includes('link') || name.includes('drop link')) return stabilizerLinkImg;
  if (name.includes('serpentine') || name.includes('belt') || name.includes('sapentine') || name.includes('fan belt') || name.includes('timing belt')) return serpentineBeltImg;
  if (name.includes('fuel pump') || name.includes('petrol pump') || name.includes('diesel pump') || name.includes('fuel module')) return fuelPumpImg;
  if (name.includes('oil filter') || name.includes('lube filter') || name.includes('oil cartridge')) return oilFilterImg;
  if (name.includes('air filter') || name.includes('cleaner element') || name.includes('intake filter')) return airFilterImg;
  if (name.includes('spark') || name.includes('plug') || name.includes('glow plug') || name.includes('iridium')) return sparkPlugsImg;
  if (name.includes('clutch') || name.includes('pressure plate') || name.includes('release bearing')) return clutchKitImg;
  if (name.includes('oxygen') || name.includes('o2') || name.includes('sensor') || name.includes('lambda') || name.includes('airflow') || name.includes('maf')) return oxygenSensorImg;
  if (name.includes('water pump') || name.includes('coolant pump')) return waterPumpImg;
  if (name.includes('compressor') || name.includes('a/c') || name.includes('ac pump') || name.includes('air condition')) return acCompressorImg;
  if (name.includes('control arm') || name.includes('wishbone') || name.includes('ball joint') || name.includes('suspension arm')) return controlArmImg;

  return fallback || brakePadsImg;
}

